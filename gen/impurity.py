"""Species-resolved impurity fate through the DS train, generated from data/impurities.csv.

This carries the purity-floor argument NUMERICALLY rather than only in prose: block-internal
n-1 is floored at the blocks (EQ-PURITY, computed from P-BLOCK-PUR); small solutes are cleared
quantitatively by diafiltration (EQ-DIAF, from P-DF-DIAVOL); whole-block impurities are sized at
introduction (1 - P-LIG-CONV); and every class whose clearance has no oligo-specific number is
rendered as a registered gap rather than invented.

Unlike the mass/energy balance this overlay is LENIENT: it reads with param_value (-> None) and
renders 'gap (...)' instead of raising, so a missing clearance number never takes down the balance.
Impurity fate is a set of FRACTIONS and is independent of annual demand (Q-002).
"""
import math

from .dataio import load_rows, load_params, param_value
from .balance import purity_floor

BANNER = ("<!-- GENERATED by gen/impurity.py from data/impurities.csv - do not edit by hand. "
          "Edit the CSV source instead. -->\n\n")


#: Clearance models this overlay knows how to render. A typo in the CSV must not silently fall
#: through to a claimed "registered gap" - the same reason sources.csv has a controlled vocabulary.
CLEARANCE_MODELS = {
    "block_floor",            # set at the blocks; no downstream separation can improve it
    "block_clearable",        # differs by a whole block, so UF/DF can clear it
    "diafiltration",          # small solute, quantitatively cleared by buffer exchange
    "particulate",            # removed by depth / 0.2 um filtration
    "designed_out",           # genuinely absent by design
    "controlled_at_reaction",  # suppressed where it forms; NOT demonstrated, so residual is open
    "gap",                    # no oligo-specific clearance number exists
}


def _fate(row, params):
    """Residual/fate of one impurity class at drug substance, computed leniently.

    Gaps render their REGISTERED reference (gap_ref), so a gap is shown as registered and the
    reader can reach the register entry. Previously three rows read "(see notes)" on a page with
    no notes column, which pointed at nothing.
    """
    model = row["clearance_model"]
    ref = (row.get("gap_ref") or "").strip()
    if model not in CLEARANCE_MODELS:
        raise ValueError(
            f"{row['impurity_id']}: unknown clearance_model {model!r}; "
            f"expected one of {sorted(CLEARANCE_MODELS)}"
        )
    if model == "block_floor":
        floor = purity_floor()
        return (f"not cleared - sets the full-length ceiling at {floor:.1f}%. The remaining "
                f"{100 - floor:.1f}% is non-full-length block material, of which only the "
                f"internal deletions are unclearable (R-018 distinguishes truncations) (EQ-PURITY)")
    if model == "diafiltration":
        n = param_value(params, "P-DF-DIAVOL")
        if n is None:
            return f"cleared by diafiltration - gap ({ref or 'Q-020'})"
        cleared = (1.0 - math.exp(-n)) * 100.0
        return (f"{cleared:.1f}% cleared at {n:.0f} diavolumes, assuming sieving ~1 "
                f"(EQ-DIAF)")
    if model == "block_clearable":
        conv = param_value(params, "P-LIG-CONV")
        intro = "an unquantified share" if conv is None else f"~{100 - conv:.0f}%"
        return (f"introduced {intro} at ligation; UF/DF-clearable but the residual "
                f"is a gap ({ref or 'Q-036'})")
    if model == "particulate":
        return "cleared by 0.2 um / depth filtration"
    if model == "designed_out":
        return "genuinely absent by design - no downstream separation needed"
    if model == "controlled_at_reaction":
        return (f"suppressed where it forms, not removed downstream - but that suppression is "
                f"proposed, not demonstrated, so the residual at DS is an open gap ({ref})")
    return f"not quantified - registered gap ({ref})" if ref else "not quantified - registered gap"


def render():
    params = load_params()
    rows = load_rows("impurities")
    floor = purity_floor()
    diavol = param_value(params, "P-DF-DIAVOL")
    dv_cleared = None if diavol is None else (1.0 - math.exp(-diavol)) * 100.0

    body = BANNER + "# Species-resolved impurity fate\n\n"
    body += ("!!! warning \"Assumption-driven, and a fraction picture\"\n"
             "    Every fraction here is computed from the same assumption-flagged inputs as the "
             "balance (`P-BLOCK-PUR`, `P-LIG-CONV`, `P-DF-DIAVOL`) and is a **fate fraction**, "
             "independent of annual demand (Q-002). Classes with no oligo-specific clearance number "
             "are shown as registered **gaps**, never invented. Provenance and the source travel in "
             "the table's own columns.\n\n")

    nblocks = param_value(params, "P-N-BLOCKS")
    nb = f"{nblocks:.0f} blocks" if nblocks is not None else "the registered block count"
    body += ("The two quantities the purity argument turns on are computable now. The block-ligation "
             f"**full-length ceiling is {floor:.1f}%** (`EQ-PURITY`: {nb} at `P-BLOCK-PUR`, "
             "`P-N-BLOCKS`), which block-internal n-1 fixes and no filtration mode can raise. "
             "Small solutes clear "
             + (f"to **{dv_cleared:.1f}%** at {diavol:.0f} diavolumes " if dv_cleared is not None
                else "by diafiltration ")
             + "(`EQ-DIAF`). Everything between those two - whole-block species, the enzyme, "
             "divalent cations, endotoxin - is where the gaps sit.\n\n")

    cols = ["Impurity class", "Size vs product", "Introduced", "Cleared by",
            "Fate to drug substance", "Provenance"]
    lines = ["| " + " | ".join(cols) + " |",
             "| " + " | ".join("---" for _ in cols) + " |"]
    for r in rows:
        prov = r.get("provenance", "")
        src = (r.get("source_key") or "").strip()
        prov_cell = f"{prov} ({src})" if src else prov
        cell = [
            r["name"],
            r.get("size_vs_product", ""),
            r.get("intro_stream", ""),
            r.get("cleared_by", ""),
            _fate(r, params),
            prov_cell,
        ]
        lines.append("| " + " | ".join(c.replace("|", "\\|") for c in cell) + " |")
    body += "\n".join(lines) + "\n\n"

    body += ("The single-nucleotide job that filtration cannot do is done at the **block stage**, on "
             "short blocks, and pushed to the block supplier (see the "
             "[filtration finding](../findings/filtration.md)); inside the facility no "
             "single-nucleotide separation is attempted. The full qualitative clearance matrix, with "
             "per-mode bases, is on the [filtration process page](../process/filtration.md).\n")
    return body
