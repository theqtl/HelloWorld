def concentration_to_vessel():
    """What each endpoint of the concentration evidence would imply for the reactor.

    The bridge from a range to a facility, and the reason the endpoints are presented SEPARATELY
    rather than as a band: `ENV-006`'s verdict is `not_a_range`, one end being a demonstrated
    success and the other a reported failure, so an interpolation between them would assert
    operating points nobody has reached. Each endpoint is instead run through the balance on its own
    and labelled with what kind of claim it is.

    Re-uses the deep-copy trick from gen/build.py::_excipient_sensitivity - perturb a copy of the
    param dict, never a CSV - so this table cannot drift from the model it reports.
    """
    from .balance import run_scenario
    params = load_params()
    mw = _num(params.get("P-MW-DUPLEX", {}).get("value"))
    scn = load_rows("scenarios")[0]
    env = [r for r in load_rows("envelopes") if r["envelope_id"] == "ENV-006"]
    if not env or mw is None:
        return None, None
    env = env[0]
    rows = []
    for end, label in (("low", "low endpoint"), ("high", "high endpoint")):
        conc_mM = _num(env[end])
        if conc_mM is None:
            continue
        # mM of a duplex of mass `mw` Da is mM * mw / 1000 g/L. Arithmetic ours, stated as such.
        conc_g_L = conc_mM * mw / 1000.0
        p = {k: dict(v) for k, v in params.items()}
        p["P-CONC-LIG"]["value"] = f"{conc_g_L:g}"
        r = run_scenario(scn, p)
        rows.append({
            "Endpoint": f"`{env['param_id']}` {label} = {_g(conc_mM)} mM",
            "As a titre, at best (`P-MW-DUPLEX`)": f"{_g(conc_g_L)} g/L",
            "Ligation batch volume": f"{r.ligation_volume_L:,.1f} L",
            "Source": f"[{env[end + '_source_key']}](../registers/sources.md)",
            "What kind of claim": ("**a demonstrated success** — but on an all-phosphodiester "
                                   "backbone (Q-064)" if end == "low" else
                                   "**a reported failure** — the volume is what it *would* be if "
                                   "it worked (Q-064)"),
        })
    return env, rows


def clearance_duty():
    """The residual-protein clearance DUTY each enzyme branch implies, per candidate limit.

    Two quantities were being conflated, and separating them is the point of this table. The DUTY -
    how many logs must be cleared - is computable from a branch's loading and the process
    concentration. The ACHIEVED log reduction is what `P-ENZ-CLEARANCE-LRV` holds, and it has no
    endpoint in either branch, so it stays blank. A duty must never migrate into that field: they
    are different quantities and one of them is a requirement while the other is a result.

    The candidate limits are labelled CANDIDATES on purpose. No residual-ligase limit exists (Q-060)
    - the EU oligonucleotide guideline omits protein entirely and offers only toxicological
    qualification - so the duty is carried as a band across candidate limits rather than at a point,
    the same treatment the endotoxin duty gets.

    The immobilised branch returns a blank rather than a number, and that blank is the finding: its
    loading is a mass of carrier solid with no immobilisation yield stated anywhere, so no protein
    mass can be recovered from it.
    """
    params = load_params()
    conc = _num(params.get("P-CONC-LIG", {}).get("value"))
    if conc is None:
        return None, []
    candidates = (100.0, 1.0)
    rows = []
    for r in load_rows("envelopes"):
        if r["param_id"] != "P-LIG-ENZ-LOAD":
            continue
        branch = r["notes"].split(".")[0].replace("BRANCH: ", "")
        load = _num(r["low"])
        cell = {"Branch": f"`{r['envelope_id']}` — {_esc(branch)}",
                "Loading": f"{_g(load)} {r['units'].replace('_', ' ')}",
                "Source": f"[{r['low_source_key']}](../registers/sources.md)"}
        if r["units"] != "mg_carrier_solid" and load is not None:
            ng_per_mg = load / conc * 1e6
            cell["Entering, per mg of product"] = f"{ng_per_mg:,.0f} ng/mg (`P-CONC-LIG`)"
            import math
            for lim in candidates:
                cell[f"Duty to {_g(lim)} ng/mg"] = f"{math.log10(ng_per_mg / lim):.2f} log"
        else:
            cell["Entering, per mg of product"] = "**gap** — no immobilisation yield (Q-032)"
            for lim in candidates:
                cell[f"Duty to {_g(lim)} ng/mg"] = "—"
        rows.append(cell)
    return conc, rows


def _split_table():
    """The four-way split, counted from the register rather than asserted."""
    needs = load_rows("infoneeds")
    total = len(needs)
    label = {
        "bracketed_evidence": "answered by a band whose endpoints are published measurements",
        "bracketed_argument": "answered by a band bracketed from physical or chemical argument",
        "point_justified": "answered by ONE value, with a written reason why no range is needed",
        "not_knowable": "**cannot be answered from the public record at all**",
    }
    rows = []
    for d in ("bracketed_evidence", "bracketed_argument", "point_justified", "not_knowable"):
        hit = [r["need_id"] for r in needs if r["disposition"] == d]
        rows.append({"Disposition": f"`{d}`", "What it means": label[d],
                     "Rows": f"{len(hit)} of {total}",
                     "Which": ", ".join(hit) or "—"})
    return total, rows


