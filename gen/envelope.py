"""The ligation design envelope, generated from the four registers this slice added.

Three things in this repository were prose and so could not be checked, and each of them had
already failed silently:

1. A BAND'S TWO ENDPOINTS WERE ONE CITATION WEARING TWO. `parameters.csv` carries a single
   `source_key` per row, so a range whose ends came from one document looked exactly like a range
   bracketed by two independent ones. `P-BLOCK-PUR` was that defect at its worst - both ends from
   one patent, one of them a bench datum inside a band labelled hectogram, and its point value a
   YIELD misread as a purity. `envelopes.csv` gives each endpoint its own `source_key` and its own
   `scale_system`, and a `bracket_verdict` saying what the pair actually is.

2. A STACK OF RANGES IS NOT A REGION. Two parameters can each sit inside their band while the
   corner they form together is unreachable, and nothing could express that. ICH Q8(R2) Appendix 2
   addresses exactly this case and sanctions either the true curved region or a smaller INSCRIBED
   box - never a circumscribed one. `couplings.csv` declares the unreachable corners and
   `corner_rule_offenders` below turns that into arithmetic: a `design_intent` band may not span a
   corner a coupling has declared unreachable.

3. AN INFORMATION REQUIREMENT'S ANCHOR WAS INVISIBLE. Every row of the checklist can quote a clause
   for its CATEGORY, but almost none can quote one for an enzymatic step - `enzym` and `biocatal`
   return zero hits across ICH Q11 and Q7, and the one in-force oligonucleotide guideline expressly
   declines the route. `infoneeds.anchor_strength` carries `direct` versus `generic_anchor` so the
   checklist cannot read as though regulators had specified this process.

Like `gen/controls.py` and `gen/impurity.py` this module is LENIENT on blanks (a blank renders as a
registered gap with a live reference, never as a number) and STRICT on vocabulary (an unknown value
raises rather than rendering as a confident statement). Every figure on the page is COMPUTED from the
registers - none is typed into a format string - so a register edit moves the page and the guards
together, which is the whole reason the defects above were able to hide in prose.
"""
import re

from .dataio import load_rows, load_params, RANGE_KINDS, RANGE_KINDS_ICH
from .tables import md_table

BANNER = ("<!-- GENERATED by gen/envelope.py from data/envelopes.csv, data/couplings.csv, "
          "data/infoneeds.csv and data/verdicts.csv - do not edit by hand. Edit the CSV source "
          "instead. -->\n\n")

#: What the two endpoints of a band ACTUALLY are. This is the column the slice exists for: a width
#: says how far apart two numbers are and says nothing about whether they are two claims or one.
BRACKET_VERDICTS = {
    "two_independent",              # two endpoints citing two DIFFERENT sources. The only verdict
                                    # under which a band is a band without qualification.
    "one_source_both_ends",         # both endpoints citing the SAME source. NOT automatically
                                    # refused - a band may still be the honest summary of what one
                                    # study found - but the register has to disclose it.
    "no_source_either_end",         # neither endpoint cites a source, because neither is a citation:
                                    # the span is bracketed by argument, or it is a choice this
                                    # project is making. Legitimate, and must not be dressed up as
                                    # anything else.
    "measurement_plus_unverifiable",  # one endpoint verified against its document, one whose
                                    # document could not be re-read. Carried and labelled, never
                                    # presented as two measurements.
    "not_a_range",                  # the two ends are different KINDS of claim - a success and a
                                    # failure, or two bases with a switched denominator - so no width
                                    # between them is a window of operation. A parameter with this
                                    # verdict must carry NO range of that kind in parameters.csv, and
                                    # `range_written_where_refused` enforces it.
    "single_point",                 # one endpoint only, in this branch's own units: low == high. The
                                    # per-branch enzyme loadings are this, because their units do not
                                    # convert into one another at all.
}
# WHY THIS COLUMN ASKS EXACTLY ONE QUESTION. An earlier version of this vocabulary carried a
# `measurement_plus_argument` value, and the acceptance panel caught it labelling two rows that have
# no measured endpoint at all - `P-EPS-260`, which states "NO SOURCE AT EITHER END, by construction",
# and the evaporator's `design_intent` band, whose endpoints are explicitly ours and not measured. The
# fault was structural rather than clerical: that value mixed "how many independent citations do the
# endpoints have" with "is this band measured or argued", and the second question is ALREADY answered
# by `range_kind` (evidence versus argued versus design_intent). One column, one question - so every
# verdict below is now checkable against the row's own data, which is what let the guard find nothing
# wrong before.

#: Verdicts under which a numeric interval may be published as a range at all.
BRACKET_VERDICTS_RANGEABLE = frozenset(BRACKET_VERDICTS - {"not_a_range", "single_point"})

#: How two parameters pull on each other.
COUPLING_DIRECTIONS = {
    "opposed",                   # raising one lowers the achievable value of the other
    "competing",                 # both draw on one finite pool (free magnesium, in the live case)
    "independent_but_confused",  # NOT actually coupled - the row exists because the register
                                 # treated them as though they were, and the correction needs a home
}

#: Which corner of the two bands a coupling speaks about.
CORNERS = {"low_low", "low_high", "high_low", "high_high"}

#: Whether that corner can be reached. `unknown` is a real answer and must stay available: the ATP
#: coupling's corner was previously asserted unreachable on a reading of one sentence that stripped
#: its context, and `unknown` is what the evidence actually supports.
CORNER_REACHABLE = {"yes", "no", "unknown"}

#: How an information requirement is currently answered. The four-way split.
DISPOSITIONS = {
    "bracketed_evidence",   # answered by a band whose endpoints are published measurements
    "bracketed_argument",   # answered by a band bracketed from physical or chemical argument
    "point_justified",      # answered by ONE value, with a stated reason why no range is needed.
                            # A bare point value is a claim that the variable does not matter, and
                            # that claim needs defending - so `point_argument` may not be blank.
    "not_knowable",         # cannot be answered from the public record at all
}

#: Whether a clause can be quoted for the enzymatic step itself, or only for the category above it.
ANCHOR_STRENGTHS = {
    "direct",          # the cited clause speaks to the thing being done
    "generic_anchor",  # the clause demands the CATEGORY; the enzyme-specific reading is ours
}

#: The acceptance panel's two possible answers. Deliberately binary and deliberately not averaged.
VERDICT_VALUES = {"ACCEPT", "REJECT"}

#: ICH Q11 s10.3, verbatim, and the honest frame for the whole page: it says what a range of
#: successful operation does and does not license. Verified twice against two independent extractions
#: of the retrieved guideline.
ICH_Q11_HONESTY = (
    "Operation beyond these ranges does not necessarily mean that drug substance of unacceptable "
    "quality will be produced, simply that these operating conditions have not been studied and "
    "therefore the quality of the drug substance is unknown."
)


def _esc(text):
    return (text or "").replace("|", "\\|").replace("\n", " ").strip()


def _refs(value):
    return [t.strip() for t in (value or "").split(";") if t.strip()]


def _num(raw):
    """Float or None. Mirrors param_value's contract: a blank stays None, never becomes a number."""
    raw = (raw or "").strip()
    if raw == "":
        return None
    try:
        return float(raw)
    except ValueError:
        return None


def _g(v):
    """Render a float without trailing noise, so a computed figure reads like a stated one."""
    return f"{v:,.0f}" if abs(v - round(v)) < 1e-9 else f"{v:,.2f}".rstrip("0").rstrip(".")


def drives_universe():
    """Everything an endpoint may say it drives: the things that get built or bought.

    Computed as a union rather than listed, so adding an equipment item or a utility does not
    silently narrow what the register is allowed to point at.
    """
    out = set()
    for name, col in (("equipment", "equip_id"), ("utilities", "utility_id"),
                      ("controls", "control_id"), ("instruments", "instrument_id")):
        out |= {r[col] for r in load_rows(name)}
    return out


def satisfied_universe():
    """Everything an information need may claim to be satisfied by."""
    out = set(drives_universe())
    for name, col in (("parameters", "param_id"), ("envelopes", "envelope_id"),
                      ("couplings", "coupling_id"), ("buffers", "buffer_id"),
                      ("impurities", "impurity_id"), ("risks", "risk_id")):
        out |= {r[col] for r in load_rows(name)}
    return out


def validate():
    """Raise on any vocabulary or referential error in the four new registers.

    Strict on vocabulary for the reason gen/controls.py gives: a typo must not fall through to a
    confident statement about the process. The checks that go beyond "is this value spelled right"
    are the ones that make the registers self-correcting:

      * a `two_independent` verdict whose two endpoints cite the SAME source is a verdict
        contradicting its own data, and vice versa for `one_source_both_ends`;
      * a `single_point` row whose two ends differ is not a point;
      * a `point_justified` information need with no `point_argument` is a bare point value with
        nothing defending it, which is the defect the four-way split exists to surface.
    """
    params = load_params()
    problems = []
    universe = drives_universe()
    sources_by_key = {r["source_key"]: r for r in load_rows("sources")}

    for r in load_rows("envelopes"):
        eid = r["envelope_id"]
        if r["param_id"] not in params:
            problems.append(f"{eid}: param_id {r['param_id']} does not resolve")
        if r["range_kind"] not in RANGE_KINDS:
            problems.append(f"{eid}: range_kind {r['range_kind']!r} is not in the controlled "
                            f"vocabulary; expected one of {sorted(RANGE_KINDS)}")
        elif r["range_kind"] in RANGE_KINDS_ICH:
            problems.append(
                f"{eid}: range_kind {r['range_kind']!r} is an ICH term of art and is deliberately "
                f"EMPTY in this repository - nothing here has been demonstrated to provide "
                f"assurance of quality, and nothing was characterised by us")
        verdict = r["bracket_verdict"]
        if verdict not in BRACKET_VERDICTS:
            problems.append(f"{eid}: bracket_verdict {verdict!r} is not in the controlled "
                            f"vocabulary; expected one of {sorted(BRACKET_VERDICTS)}")
        lo, hi = _num(r["low"]), _num(r["high"])
        if lo is None or hi is None:
            problems.append(f"{eid}: low/high are not both numeric: {r['low']!r}, {r['high']!r}")
        elif lo > hi:
            problems.append(f"{eid}: low {lo} is above high {hi}")
        elif verdict == "single_point" and lo != hi:
            problems.append(
                f"{eid}: bracket_verdict single_point but low {lo} != high {hi}; a point that "
                f"spans an interval is a band, and a band needs a verdict that says whose two "
                f"claims its ends are")
        # Every source-shaped verdict is checked against the row's OWN endpoints, so a verdict
        # cannot contradict its own data. The acceptance panel found exactly that defect in the
        # first version of this register - two rows claiming a measured endpoint while their own
        # scale_system said "NO SOURCE AT EITHER END" - because the vocabulary then mixed two
        # questions and no check could reach the second one. See the note under BRACKET_VERDICTS.
        lsk, hsk = r["low_source_key"].strip(), r["high_source_key"].strip()
        if verdict == "two_independent" and (not lsk or not hsk or lsk == hsk):
            problems.append(
                f"{eid}: bracket_verdict two_independent, but the endpoints cite {lsk!r} and "
                f"{hsk!r} - two independent endpoints means two different documents, and this "
                f"verdict contradicts its own data")
        if verdict == "one_source_both_ends" and (not lsk or lsk != hsk):
            problems.append(
                f"{eid}: bracket_verdict one_source_both_ends, but the endpoints cite {lsk!r} and "
                f"{hsk!r} - that verdict means ONE named source at both ends")
        if verdict == "no_source_either_end" and (lsk or hsk):
            problems.append(
                f"{eid}: bracket_verdict no_source_either_end, but an endpoint cites a source "
                f"({lsk!r}, {hsk!r}). A band bracketed by argument must not carry a citation that "
                f"would be read as measuring it; a band with a citation needs a verdict saying "
                f"whose claim it is")
        if verdict in ("two_independent", "one_source_both_ends",
                       "measurement_plus_unverifiable") and not (lsk and hsk):
            problems.append(
                f"{eid}: bracket_verdict {verdict} names a sourced endpoint pair, but "
                f"low_source_key={lsk!r} and high_source_key={hsk!r} - use no_source_either_end "
                f"if neither end is a citation")
        for col in ("low_source_key", "high_source_key"):
            key = (r.get(col) or "").strip()
            if key and key not in sources_by_key:
                problems.append(f"{eid}: {col} {key} is not in the source register")
        for col in ("low_drives_ref", "high_drives_ref"):
            for ref in _refs(r.get(col)):
                if ref not in universe:
                    problems.append(f"{eid}: {col} {ref} resolves to no equipment, utility, "
                                    f"control or instrument")

    for r in load_rows("couplings"):
        cid = r["coupling_id"]
        for col in ("param_a", "param_b"):
            if r[col] not in params:
                problems.append(f"{cid}: {col} {r[col]} does not resolve")
        if r["direction"] not in COUPLING_DIRECTIONS:
            problems.append(f"{cid}: direction {r['direction']!r} is not in the controlled "
                            f"vocabulary; expected one of {sorted(COUPLING_DIRECTIONS)}")
        if r["corner"] not in CORNERS:
            problems.append(f"{cid}: corner {r['corner']!r} is not one of {sorted(CORNERS)}")
        if r["corner_reachable"] not in CORNER_REACHABLE:
            problems.append(f"{cid}: corner_reachable {r['corner_reachable']!r} is not one of "
                            f"{sorted(CORNER_REACHABLE)}")
        key = (r.get("source_key") or "").strip()
        if key and key not in sources_by_key:
            problems.append(f"{cid}: source_key {key} is not in the source register")
        for ref in _refs(r.get("bites_ref")):
            if ref not in universe:
                problems.append(f"{cid}: bites_ref {ref} resolves to no equipment, utility, "
                                f"control or instrument")

    sat = satisfied_universe()
    for r in load_rows("infoneeds"):
        nid = r["need_id"]
        if r["disposition"] not in DISPOSITIONS:
            problems.append(f"{nid}: disposition {r['disposition']!r} is not in the controlled "
                            f"vocabulary; expected one of {sorted(DISPOSITIONS)}")
        if r["anchor_strength"] not in ANCHOR_STRENGTHS:
            problems.append(f"{nid}: anchor_strength {r['anchor_strength']!r} is not one of "
                            f"{sorted(ANCHOR_STRENGTHS)}")
        if r["disposition"] == "point_justified" and not (r.get("point_argument") or "").strip():
            problems.append(
                f"{nid}: disposition point_justified with a blank point_argument. A bare point "
                f"value is a claim that the variable does not matter; that claim has to be made "
                f"in writing or the row is an unflagged placeholder")
        if r["disposition"] != "point_justified" and (r.get("point_argument") or "").strip():
            problems.append(
                f"{nid}: point_argument is populated but the disposition is "
                f"{r['disposition']!r} - an argument for a point value on a row that carries no "
                f"point value will be read as justifying something it does not")
        clause = (r.get("anchor_clause") or "").strip()
        if not clause:
            problems.append(f"{nid}: no anchor_clause - an information requirement with no "
                            f"citable clause is our opinion, and must not sit in this register")
        else:
            # AND THE CLAUSE HAS TO EXIST. Checking only that the field is non-blank was the hole
            # the acceptance panel walked through: four rows anchored to "ICH Q11 s4.3", and ICH
            # Q11 section 4 has no numbered subsections at all - the only "4.3" in the document is
            # a CTD pointer. A fabricated clause number is the same defect as a fabricated
            # measurement, and it passed 105 green tests.
            #
            # The check couples the two registers: every clause an information need cites must
            # appear in its source row's `clauses_read`. That is deliberately a documentation
            # obligation rather than a text search of the PDF - the documents are not in the repo,
            # and a source row that cannot say it read the clause it is cited for has no business
            # being the anchor.
            #
            # `clauses_read` IS A COLUMN AND NOT A SEARCH OF `notes`, because the first version of
            # this guard searched the notes and blessed the very clause it was written to refuse:
            # the corrective sentence added to SRC-ICH-Q11 - "there is no s4.1, s4.2 or s4.3 to
            # cite" - contains the string "s4.3", so a substring check found it and passed. A guard
            # that a row's own prose can satisfy by DENYING the clause is worse than no guard, and
            # only a delimited field is safe from that.
            src = sources_by_key.get(r.get("anchor_source_key", "").strip())
            if r.get("anchor_source_key", "").strip() and src is None:
                problems.append(f"{nid}: anchor_source_key {r['anchor_source_key']!r} does not "
                                f"resolve")
            elif src is not None:
                read = {c.strip().lower()
                        for c in (src.get("clauses_read") or "").split(";") if c.strip()}
                for part in [c.strip() for c in clause.split(" and ") if c.strip()]:
                    if part.lower() not in read:
                        problems.append(
                            f"{nid}: anchor_clause cites {part!r} of "
                            f"{r['anchor_source_key']}, but that source's clauses_read does not "
                            f"list it ({sorted(read) or 'empty'}) - record the clause as read, or "
                            f"cite one that exists")
        for ref in _refs(r.get("satisfied_by")):
            if ref not in sat:
                problems.append(f"{nid}: satisfied_by {ref} resolves to nothing")

    qids = {r["question_id"] for r in load_rows("questions")}
    for r in load_rows("verdicts"):
        vid = r["verdict_id"]
        if r["verdict"] not in VERDICT_VALUES:
            problems.append(f"{vid}: verdict {r['verdict']!r} is not one of "
                            f"{sorted(VERDICT_VALUES)}")
        blocker = (r.get("blocker_ref") or "").strip()
        if blocker not in qids:
            problems.append(
                f"{vid}: blocker_ref {blocker!r} is not a registered question id. A reviewer's "
                f"binding blocker has to be something this repository already tracks, or the "
                f"panel is generating new work rather than judging the existing register")
        if not (r.get("what_would_change_it") or "").strip():
            problems.append(f"{vid}: no what_would_change_it - a verdict that cannot be moved is "
                            f"an opinion, not a review finding")

    if problems:
        raise ValueError("envelope register problem(s): " + "; ".join(problems))


def range_written_where_refused():
    """param_ids whose envelope says the span is NOT a range while parameters.csv writes one.

    This is standing decision 2 made mechanical. A bracket that fails the two-independent-endpoints
    test keeps a blank or a clearly-labelled single point in the parameter register, and the failure
    becomes a registered question - so a `not_a_range` verdict here and a numeric range there is a
    direct contradiction between two registers, and it is the exact shape of the defect this slice
    was built to stop.
    """
    params = load_params()
    offenders = []
    for r in load_rows("envelopes"):
        if r["bracket_verdict"] != "not_a_range":
            continue
        p = params.get(r["param_id"])
        if not p:
            continue
        lo = (p.get("range_low") or "").strip()
        hi = (p.get("range_high") or "").strip()
        kind = (p.get("range_kind") or "").strip()
        if lo and hi and kind == r["range_kind"]:
            offenders.append(
                f"{r['param_id']}: envelopes.csv {r['envelope_id']} rules the "
                f"{r['range_kind']} span not_a_range, but parameters.csv writes it as "
                f"{lo}-{hi}")
    return offenders


def envelope_by_param():
    """{(param_id, range_kind): row} for every audited band."""
    return {(r["param_id"], r["range_kind"]): r for r in load_rows("envelopes")}


def unaudited_bands():
    """Numeric ranges in parameters.csv with no endpoint audit in envelopes.csv.

    One-directional ON PURPOSE. Every band a consumer can read off `parameters.csv` must have an
    audit, because that is the number they will use. The reverse does not hold and must not: three
    envelope rows deliberately have no counterpart there - `P-BLOCK-PUR`'s argued band, because
    `range_kind` is one value per row and the parameter already spends it on the measured band; and
    the `not_a_range` and `single_point` rows, which exist precisely to record spans that must NOT
    be written as ranges.

    This is the guard the acceptance panel asked for, and it replaces the thing it asked for. The
    reviewer's point was that `one_source_both_ends` is disclosed in `envelopes.csv` and not beside
    the number in `parameters.csv`, so the disclosure does not reach whoever reads the parameter. The
    fix is not to copy the verdict into a second column - carrying a relation on both sides lets the
    two disagree with nothing to detect it, which is why `instruments.csv` has no `control_loop`
    column. It is to require that the audit EXISTS and to render it beside the parameter at build
    time, joined rather than duplicated (see gen/build.py).
    """
    audited = envelope_by_param()
    missing = []
    for r in load_rows("parameters"):
        lo = (r.get("range_low") or "").strip()
        hi = (r.get("range_high") or "").strip()
        kind = (r.get("range_kind") or "").strip()
        if lo and hi and (r["param_id"], kind) not in audited:
            missing.append(
                f"{r['param_id']} carries a {kind or '(blank)'} range {lo}-{hi} with no endpoint "
                f"audit in envelopes.csv, so nothing states whether its two ends are two claims "
                f"or one")
    return missing


def verdict_for(pid, kind):
    """The bracket verdict to render beside a parameter's band, or None."""
    row = envelope_by_param().get((pid, kind))
    return row["bracket_verdict"] if row else None


def purity_ceiling_sensitivity():
    """The drug-substance full-length ceiling at each candidate block purity.

    The acceptance panel's process reviewer made this the condition of acceptance, and the objection
    is a fair one: `P-BLOCK-PUR`'s point value is raised to the power of `P-N-BLOCKS` to publish the
    full-length ceiling, every measurement behind it is a different chemistry from the material
    S01/S02 receive, and the nearest-chemistry datum - 81% for a 6-mer 2'-OMe PS, OUR backbone - sits
    12.6 points below the band and is excluded. The exclusion is argued in ENV-001 and stands, but
    its CONSEQUENCE was invisible, and an exclusion whose cost is not shown is indistinguishable from
    one made because it flatters the route.

    So the cost is computed here at every candidate, from the register's own `purity_floor`. No
    number is typed in: change `P-N-BLOCKS` and every row moves.
    """
    from .balance import purity_floor
    params = load_params()
    n = params.get("P-N-BLOCKS", {}).get("value", "")
    env = envelope_by_param()
    cases = []
    e1 = env.get(("P-BLOCK-PUR", "evidence"))
    e2 = env.get(("P-BLOCK-PUR", "argued"))
    pt = _num(params.get("P-BLOCK-PUR", {}).get("value"))
    if e1:
        cases += [(_num(e1["low"]), f"measured band, low end ({e1['envelope_id']})", e1["low_source_key"]),
                  (_num(e1["high"]), f"measured band, high end ({e1['envelope_id']})", e1["high_source_key"])]
    if pt is not None:
        cases.append((pt, "the registered point value, which is what is published today", "SRC-WO2020227618"))
    if e2:
        cases += [(_num(e2["low"]), f"argued band, low end ({e2['envelope_id']})", e2["low_source_key"]),
                  (_num(e2["high"]), f"argued band, high end ({e2['envelope_id']})", e2["high_source_key"])]
    cases.append((81.0, "OUR backbone, wrong topology - a 6-mer 2'-OMe PS, excluded from the band "
                        "(ENV-001, Q-057)", "SRC-KELLY-OPRD-2025"))
    # Two candidates can coincide - the registered point value IS the measured band's low end
    # today - and two identical rows read as a mistake rather than as the fact that they agree.
    # Merge on the value and keep both descriptions.
    merged = {}
    for f, label, src in cases:
        if f is None:
            continue
        if f in merged:
            merged[f][0] = merged[f][0] + "; also " + label
        else:
            merged[f] = [label, src]
    rows = []
    for f in sorted(merged):
        label, src = merged[f]
        rows.append({
            "Block full-length purity": f"{_g(f)} %",
            "What that figure is": label,
            "Source": f"[{src}](../registers/sources.md)" if src else "—",
            f"DS full-length ceiling at `P-N-BLOCKS` = {n}": f"**{purity_floor(f):.1f} %**",
        })
    return n, rows


def corner_rule_offenders():
    """design_intent bands that span a corner a coupling has declared unreachable.

    ICH Q8(R2) Appendix 2 s C Example 1 is explicit that where one parameter's acceptable range
    depends on another's, an applicant may report the true region OR a smaller box - and the box has
    to be INSCRIBED, every corner simultaneously attainable. Reporting a circumscribed box claims
    operation at corners nobody has reached.

    So: for each coupling whose `corner_reachable` is `no`, the corner names one end of each of its
    two parameters. If BOTH parameters carry a `design_intent` envelope reaching that end, the pair
    of bands asserts that corner is available, and this returns it.

    No live row trips this today, and that is expected rather than a weakness: the only
    `design_intent` band in the register is on the evaporator, which no coupling touches. The rule is
    proven by mutation instead - the same standing as `not_measurable` in gen/controls.py, which also
    has no live row and is kept because the distinction is real.
    """
    intents = {}
    for r in load_rows("envelopes"):
        if r["range_kind"] == "design_intent":
            intents.setdefault(r["param_id"], []).append(r)
    offenders = []
    for c in load_rows("couplings"):
        if c["corner_reachable"] != "no":
            continue
        ends = c["corner"].split("_")
        if len(ends) != 2:
            continue
        pair = list(zip((c["param_a"], c["param_b"]), ends))
        if all(pid in intents for pid, _ in pair):
            offenders.append(
                f"{c['coupling_id']} declares the {c['corner']} corner of "
                f"{c['param_a']} x {c['param_b']} unreachable, but both carry design_intent "
                f"bands, so the pair asserts operation at a corner nobody has reached")
    return offenders


