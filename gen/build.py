"""Generate Markdown pages from the data layer and the balance.

Run from repo root:  python -m gen.build
Writes register pages under docs/registers/, the stream table under
docs/process/, and the balance results under docs/balance/. These files are
generated: edit data/*.csv, not the generated Markdown.
"""
import os
from dataclasses import asdict

from .dataio import load_rows
from .tables import md_table
from .balance import run_all
from .flowsheet import render as render_flowsheet

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS = os.path.join(ROOT, "docs")

BANNER = ("<!-- GENERATED by gen/build.py from data/*.csv — do not edit by hand. "
          "Edit the CSV source instead. -->\n\n")


def _write(relpath, text):
    path = os.path.join(DOCS, relpath)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)
    return relpath


def gen_registers():
    written = []
    specs = [
        ("parameters", "registers/parameters.md", "Parameter register",
         "Every numeric input lives here once. `provenance` is one of **fact** "
         "(from a cited source), **inference** (our reasoning/arithmetic), or "
         "**assumption** (illustrative placeholder, registered as a gap). "
         "Blank values are unfilled gaps, never invented.", None),
        ("streams", "registers/streams.md", "Stream register",
         "Stream numbers tie to the block-flow diagram and the mass balance.", None),
        ("equipment", "registers/equipment.md", "Equipment register",
         "Sizing basis, materials of construction (MOC), and turndown per item. "
         "Most sizing is a Tier-2 gap pending the balance inputs.", None),
        ("buffers", "registers/buffers.md", "Buffer & reagent register",
         "Compositions from cited sources where available; blanks are gaps.", None),
        ("utilities", "registers/utilities.md", "Utilities register", "", None),
        ("risks", "registers/risks.md", "Risk register",
         "Sorted view of process, product, purity, and microbial risks.", None),
        ("questions", "registers/questions.md", "Open questions register",
         "The governing unknowns. Q-001 (annealing/product form) and Q-002 "
         "(real annual demand) drive the architecture and all sizing.", None),
        ("sources", "registers/sources.md", "Sources & reachability log",
         "Every citation with reachability and the scale/system it applies to.", None),
    ]
    for name, rel, title, intro, cols in specs:
        rows = load_rows(name)
        body = BANNER + f"# {title}\n\n"
        if intro:
            body += intro + "\n\n"
        body += md_table(rows, columns=cols)
        written.append(_write(rel, body))
    return written


def gen_streams_on_process():
    rows = load_rows("streams")
    body = BANNER + "# Stream table\n\n"
    body += ("Stream numbers (S01…) are referenced by the block-flow diagram and "
             "the mass balance. `stream_class` = product / buffer / waste / gas.\n\n")
    body += md_table(rows)
    return _write("process/streams.md", body)


def _fmt(v):
    return f"{v:,.1f}" if isinstance(v, float) else str(v)


def gen_balance():
    results = [asdict(r) for r in run_all()]
    body = BANNER + "# Mass & energy balance (results)\n\n"
    body += ("!!! warning \"Assumption-driven\"\n"
             "    Every number here is computed from inputs in the parameter register that are "
             "flagged **assumption** (illustrative placeholders registered as gaps). They are "
             "*not* validated values. Change `data/parameters.csv` and `data/scenarios.csv` and "
             "re-run `python -m gen.build`; every figure updates. The throughput scenarios are "
             "illustrative (see Q-002).\n\n")

    # Per-scenario key results as a comparison table
    keys = [
        ("annual_ds_api_kg", "Annual DS API (kg/yr)"),
        ("campaigns_per_yr", "Campaigns/yr"),
        ("ds_api_per_campaign_kg", "DS API per campaign (kg)"),
        ("powder_per_campaign_kg", "DS powder per campaign (kg)"),
        ("ufdf_yield_frac", "UF/DF yield (fraction)"),
        ("overall_yield_frac", "Overall yield (fraction)"),
        ("api_at_ligation_kg", "API at ligation input (kg)"),
        ("ligation_volume_L", "Ligation batch volume (L)"),
        ("uf_retentate_volume_L", "UF retentate volume (L)"),
        ("df_buffer_volume_L", "Diafiltration buffer (L)"),
        ("evap_water_removed_L", "Evaporation water removed (L)"),
        ("excip_frac_pre_evap", "Excipient fraction in solution at evaporator"),
        ("evap_outlet_solids_kg", "Evaporator outlet total solids (kg)"),
        ("dryer_feed_mass_kg", "Spray-dryer feed (kg)"),
        ("dryer_water_evaporated_kg", "Dryer water evaporated (kg)"),
        ("wfi_approx_L", "Clean water demand approx (L)"),
        ("aqueous_waste_approx_L", "Aqueous waste approx (L)"),
        ("evap_duty_MJ", "Evaporation duty (MJ)"),
        ("dryer_evap_duty_MJ", "Dryer evaporation duty (MJ)"),
    ]
    header = ["Quantity"] + [r["label"] for r in results]
    lines = ["| " + " | ".join(header) + " |",
             "| " + " | ".join("---" for _ in header) + " |"]
    for k, label in keys:
        row = [label] + [_fmt(r[k]) for r in results]
        lines.append("| " + " | ".join(row) + " |")
    body += "\n".join(lines) + "\n\n"
    body += ("All quantities are per campaign unless labelled per year. Duties are the "
             "latent-heat minimum (mass of water removed × latent heat); real evaporator and "
             "dryer duties add sensible heat, gas heating, and losses (Tier-2 energy balance).\n\n"
             "Concentrations up to and including ultrafiltration are on an siRNA basis; the "
             "evaporator outlet is on a total dissolved solids basis. How much excipient is in "
             "solution at the evaporator is an open process choice (`P-EXCIP-FRAC-PRE-EVAP`, "
             "Q-038) and it swings the evaporation duty severalfold — see the "
             "[method page](index.md).\n")
    return _write("balance/results.md", body)


def main():
    written = []
    written += gen_registers()
    written.append(gen_streams_on_process())
    written.append(gen_balance())
    written.append(_write("diagrams/bfd.svg", render_flowsheet()))
    print("Generated:")
    for w in written:
        print("  docs/" + w)


if __name__ == "__main__":
    main()
