"""Generate one process flow diagram per unit operation, docs/diagrams/pfd-<unit>.svg.

Derived from data/instruments.csv (which instruments exist and how they measure),
data/streams.csv (what flows in and out of each unit) and data/equipment.csv (the unit ops
themselves), so the drawings cannot drift from the registers the way prose did.

ONE DRAWING PER UNIT OPERATION, not one drawing for the plant. There are 49 instruments and
U05-SD alone carries 12; on a single seven-column sheet those stack into an unreadable column.
Per unit each drawing carries 4-12 bubbles, and the unit operation is the natural sheet because
every instrument row already declares a `unit_op` while only 39 of 49 declare a `stream_ref`.

WHAT THE BUBBLES MEAN, and why it is computed rather than asserted. DEXPI Process 1.0 section
2.8.2 (SRC-DEXPI-PROCESS-1-0, read in full) draws a control loop as a single bubble connected to
its sensing point "on a stream or a unit operation" - which is exactly the 39/10 split, so the ten
instruments with no stream attach to the unit box rather than being dropped. Three states, each
derived from the data by `loop_state`:

  * withdrawn  - measurement_mode is at_line or off_line, i.e. somebody carried a sample
                 somewhere. Dashed bubble, no actuator. NO LOOP CAN CLOSE ON THIS, which is the
                 entire content of the Q-042 case and the reason C-013 exists (I-024/AI-0306).
                 It must not look like a control, and it cannot: mode decides first.
  * closed     - the tag declares control (`tag_declares_control`) AND the mode is loop-capable.
                 Solid bubble plus an actuator arrow to the unit box.
  * indicating - a reading with no control function. Solid bubble, no actuator.

The actuator arrow stops at the UNIT BOX rather than at a valve because no register records which
final control element a loop manipulates. DEXPI section 2.8.1 expects a PFD to indicate it, so the
absence is registered as Q-055 and stated in the legend, not drawn as an invented valve.

The symbol set is THIS PROJECT'S OWN. DEXPI section 6 supplies the principle its section 6.2.2
states - a PFD symbol represents the activity carried out, not the equipment - but the same
section says further work is needed to define the presentation layer, so DEXPI pins no symbols;
ISO 10628-1:2014 is the standard that would (SRC-ISO-10628-1) and it is NOT retrieved; ISA-5.1 is
unread and un-reproducible. That is Q-054, and the legend says so on every drawing.

Layout is deterministic and integer-only, like gen/flowsheet.py. Marker ids are namespaced per
unit (`pfd-u05-sd-arrow`) because docs/diagrams/index.md inlines bfd.svg on the same site and bare
ids like `arrow` would collide across inlined documents and silently repaint each other's
arrowheads. `render_svg()` returns the SVG text and `render_page()` the host page; gen/build.py
writes both. Do not hand-edit the SVGs - edit data/*.csv and run `python -m gen.build`.
"""
from .controls import (
    LOOP_CAPABLE_MODES,
    WITHDRAWN_MODES,
    tag_declares_control,
)
from .dataio import load_rows
from .flowsheet import SENTINELS, UNIT_LABELS, _rank_product_nodes

BANNER = ("<!-- GENERATED by gen/pfd.py from data/instruments.csv, data/streams.csv and "
          "data/equipment.csv - do not edit by hand. Edit the CSV source instead. -->\n\n")

# Layout geometry. Integer coordinates keep the rendered output byte-stable, as in flowsheet.py.
VIEW_W = 1000
MARGIN = 24
TITLE_Y, SUBTITLE_Y = 30, 50
BOX_X, BOX_Y, BOX_W, BOX_H = 380, 72, 240, 104
IN_X = 78                  # where an inlet arrow starts
OUT_X = 922                # where an outlet arrow ends
WASTE_Y = 224              # where a waste stub ends
BAND_Y = 296               # centre of the first bubble in a stack
BUBBLE_R = 20               # fits a two-line tag; an 8-character tag on one line does not
BUBBLE_PITCH = 52
LEGEND_GAP = 46

#: Waste sink and the classes that render as a waste stub rather than a side arrow.
WASTE_CLASSES = frozenset({"waste", "gas"})


def _xml_escape(text):
    """Escape text bound for SVG character data or an attribute value.

    gen/flowsheet.py has no equivalent and gets away with it only because UNIT_LABELS overrides
    every unit it draws. This module puts registered `name` fields on the drawing, and
    equipment.csv already contains "Buffer preparation & hold suite" - a bare ampersand, which is
    not well-formed XML. So this is a live requirement, not a defensive flourish.
    """
    return (str(text or "")
            .replace("&", "&amp;")
            .replace("<", "&lt;")
            .replace(">", "&gt;")
            .replace('"', "&quot;"))


def _slug(unit_op):
    """`U03-UFDF` -> `u03-ufdf`, for filenames and namespaced marker ids."""
    return unit_op.lower()


def _clip(text, limit):
    """Shorten a registered name to fit the drawing, on a word boundary, with an ellipsis.

    A hard character slice produced "Evaporator condensate (waste" on the first pass - a truncated
    word and an unclosed bracket, on a published drawing. Trailing punctuation is stripped so the
    ellipsis never lands after a comma or an orphaned opening bracket.
    """
    text = str(text or "").strip()
    if len(text) <= limit:
        return text
    cut = text[:limit].rsplit(" ", 1)[0].rstrip(" ,;:-(/")
    return (cut or text[:limit].rstrip()) + "…"


def units():
    """The unit operations to draw, in equipment-register order.

    Derived from equipment.csv rather than hardcoded, so a new unit operation gets a drawing
    without touching this module. Sentinels are boundary placeholders with no process function
    (DEXPI section 2.6) and are never drawn as a sheet of their own.
    """
    return [r["equip_id"] for r in load_rows("equipment")
            if r["equip_id"] not in SENTINELS]


#: Evaluated once at import, mirroring how gen/build.py consumes it.
UNITS = units()


def loop_state(instrument_row):
    """`"withdrawn"`, `"closed"` or `"indicating"` for one instrument row.

    Mode is tested FIRST and wins. A tag that declares control while its reading comes off a
    withdrawn sample is a contradiction in the data, not a loop to draw: the guard
    test_a_tag_that_declares_control_is_a_loop_capable_measurement is what complains about it,
    and this function stays conservative so a lab result can never acquire an actuator arrow.
    """
    mode = (instrument_row.get("measurement_mode") or "").strip()
    if mode in WITHDRAWN_MODES:
        return "withdrawn"
    if mode in LOOP_CAPABLE_MODES and tag_declares_control(instrument_row["tag"]):
        return "closed"
    return "indicating"


def _streams_for(unit_op, streams, rank):
    """Inlet, outlet and waste streams for one unit, each ordered deterministically.

    Ordering follows the block-flow diagram's product spine where it can - a stream whose far end
    is product-ranked sorts by that rank - so the two diagrams tell the same story left to right.
    The stream id breaks every tie, so the order never depends on dict or set iteration.
    """
    def key(row, far_end):
        return (rank.get(row[far_end], 99), row["stream_id"])

    inlets = sorted((r for r in streams if r["to_unit"] == unit_op),
                    key=lambda r: key(r, "from_unit"))
    outlets = sorted((r for r in streams
                      if r["from_unit"] == unit_op
                      and r["stream_class"] not in WASTE_CLASSES),
                     key=lambda r: key(r, "to_unit"))
    wastes = sorted((r for r in streams
                     if r["from_unit"] == unit_op
                     and r["stream_class"] in WASTE_CLASSES),
                    key=lambda r: r["stream_id"])
    return inlets, outlets, wastes


def _lane_y(index, total):
    """Y centre of stream lane `index` of `total`, spread across the unit box height."""
    return BOX_Y + (BOX_H * (index + 1)) // (total + 1)


def _flow_class(stream_row):
    cls = stream_row["stream_class"]
    if cls in WASTE_CLASSES:
        return "wflow", "wid"
    if cls == "buffer":
        return "uflow", "sid"
    return "flow", "sid"


def _groups(unit_op, instruments, inlets, outlets, wastes):
    """Bubble groups, left to right, each `(label, attachment_point, [instrument rows])`.

    A group is one attachment point: a stream the unit touches, or the unit itself for the rows
    that carry no stream_ref. Order is inlets, then the unit, then outlets, then wastes, which
    keeps most leader lines from crossing without any routing cleverness.
    """
    by_stream = {}
    on_unit = []
    for r in instruments:
        ref = (r["stream_ref"] or "").strip()
        if ref:
            by_stream.setdefault(ref, []).append(r)
        else:
            on_unit.append(r)

    groups = []

    def add(rows_key, label, point):
        rows = sorted(by_stream.get(rows_key, []), key=lambda r: r["instrument_id"])
        if rows:
            groups.append((label, point, rows))

    n_in, n_out = len(inlets), len(outlets)
    for i, s in enumerate(inlets):
        add(s["stream_id"], s["stream_id"],
            ((IN_X + BOX_X) // 2, _lane_y(i, n_in)))

    if on_unit:
        groups.append((unit_op, (BOX_X + 62, BOX_Y + BOX_H),
                       sorted(on_unit, key=lambda r: r["instrument_id"])))

    for i, s in enumerate(outlets):
        add(s["stream_id"], s["stream_id"],
            ((BOX_X + BOX_W + OUT_X) // 2, _lane_y(i, n_out)))

    for i, s in enumerate(wastes):
        wx = BOX_X + BOX_W - 56 - i * 48
        add(s["stream_id"], s["stream_id"],
            (wx, (BOX_Y + BOX_H + WASTE_Y) // 2))

    return groups


def _column_x(index, total):
    """Evenly spaced column centres, so `total` bubble stacks never overlap."""
    span = VIEW_W - 2 * MARGIN
    return MARGIN + (span * (2 * index + 1)) // (2 * total)


def render_svg(unit_op):
    """The process flow diagram for one unit operation, as SVG text."""
    streams = load_rows("streams")
    equip = {r["equip_id"]: r for r in load_rows("equipment")}
    instruments = [r for r in load_rows("instruments") if r["unit_op"] == unit_op]
    instruments.sort(key=lambda r: r["instrument_id"])
    rank = _rank_product_nodes(streams)

    inlets, outlets, wastes = _streams_for(unit_op, streams, rank)
    groups = _groups(unit_op, instruments, inlets, outlets, wastes)

    deepest = max((len(rows) for _, _, rows in groups), default=0)
    band_h = deepest * BUBBLE_PITCH if deepest else 0
    view_h = BAND_Y + band_h + LEGEND_GAP
    slug = _slug(unit_op)
    name = equip.get(unit_op, {}).get("name") or unit_op
    short = UNIT_LABELS.get(unit_op, name)

    out = []
    out.append(f'<!-- GENERATED by gen/pfd.py from data/instruments.csv, data/streams.csv and '
               f'data/equipment.csv - do not edit by hand. Edit the CSV source and run '
               f'python -m gen.build. -->')
    out.append(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {VIEW_W} {view_h}" '
               f'class="pfd-svg" role="img" '
               f'aria-label="Process flow diagram of unit operation {_xml_escape(unit_op)}, '
               f'{_xml_escape(name)}, with its streams and instrument bubbles">')

    out.append('  <style>')
    out.append('    .box { fill: none; stroke: #00897b; stroke-width: 2; }')
    out.append('    .ttl { fill: currentColor; font: 700 15px sans-serif; }')
    out.append('    .lbl { fill: currentColor; font: 600 13px sans-serif; }')
    out.append('    .sub { fill: currentColor; font: 400 10px sans-serif; opacity: 0.8; }')
    out.append('    .sid { fill: #00695c; font: 700 10px sans-serif; }')
    out.append('    .wid { fill: #c62828; font: 700 10px sans-serif; }')
    out.append(f'    .flow {{ stroke: #00897b; stroke-width: 1.8; '
               f'marker-end: url(#pfd-{slug}-arrow); fill: none; }}')
    out.append(f'    .wflow {{ stroke: #c62828; stroke-width: 1.4; stroke-dasharray: 3 3; '
               f'marker-end: url(#pfd-{slug}-warr); fill: none; }}')
    out.append(f'    .uflow {{ stroke: #8e24aa; stroke-width: 1.4; stroke-dasharray: 4 3; '
               f'marker-end: url(#pfd-{slug}-uarr); fill: none; }}')
    # Instrument bubbles. A dashed ring is a withdrawn sample; the leader is deliberately a
    # different weight and colour from every flow line, which DEXPI section 4.2 requires of a
    # line that points at something rather than carrying material.
    out.append('    .bub { fill: none; stroke: #3949ab; stroke-width: 1.8; }')
    out.append('    .bubw { fill: none; stroke: #3949ab; stroke-width: 1.8; '
               'stroke-dasharray: 4 3; }')
    out.append('    .tag { fill: #3949ab; font: 700 10px sans-serif; }')
    out.append('    .lead { stroke: #78909c; stroke-width: 0.9; fill: none; }')
    out.append(f'    .act {{ stroke: #00897b; stroke-width: 1.4; '
               f'marker-end: url(#pfd-{slug}-aarr); fill: none; }}')
    out.append('  </style>')

    out.append('  <defs>')
    for mid, colour in (("arrow", "#00897b"), ("warr", "#c62828"),
                        ("uarr", "#8e24aa"), ("aarr", "#00897b")):
        out.append(f'    <marker id="pfd-{slug}-{mid}" markerWidth="9" markerHeight="9" '
                   f'refX="7" refY="3" orient="auto">'
                   f'<path d="M0,0 L7,3 L0,6 Z" fill="{colour}"/></marker>')
    out.append('  </defs>')

    # Title.
    out.append(f'  <text class="ttl" x="{MARGIN}" y="{TITLE_Y}">'
               f'{_xml_escape(unit_op)} &#183; {_xml_escape(name)}</text>')
    out.append(f'  <text class="sub" x="{MARGIN}" y="{SUBTITLE_Y}">'
               f'{len(instruments)} instrument(s) in the register for this unit operation. '
               f'Symbol set is this project’s own (Q-054); the final control element a loop '
               f'acts through is not registered (Q-055).</text>')

    # The unit box.
    out.append(f'  <rect class="box" x="{BOX_X}" y="{BOX_Y}" width="{BOX_W}" '
               f'height="{BOX_H}" rx="6"/>')
    cx = BOX_X + BOX_W // 2
    out.append(f'  <text class="lbl" x="{cx}" y="{BOX_Y + 44}" text-anchor="middle">'
               f'{_xml_escape(short)}</text>')
    out.append(f'  <text class="sub" x="{cx}" y="{BOX_Y + 64}" text-anchor="middle">'
               f'{_xml_escape(unit_op)}</text>')

    # Inlet, outlet and waste streams.
    for i, s in enumerate(inlets):
        y = _lane_y(i, len(inlets))
        cls, idc = _flow_class(s)
        out.append(f'  <path class="{cls}" d="M{IN_X},{y} L{BOX_X},{y}"/>')
        out.append(f'  <text class="{idc}" x="{IN_X}" y="{y - 7}">'
                   f'{_xml_escape(s["stream_id"])}</text>')
        out.append(f'  <text class="sub" x="{IN_X}" y="{y + 15}">'
                   f'{_xml_escape(_clip(s["name"], 34))}</text>')

    bx = BOX_X + BOX_W
    for i, s in enumerate(outlets):
        y = _lane_y(i, len(outlets))
        cls, idc = _flow_class(s)
        out.append(f'  <path class="{cls}" d="M{bx},{y} L{OUT_X},{y}"/>')
        out.append(f'  <text class="{idc}" x="{bx + 6}" y="{y - 7}">'
                   f'{_xml_escape(s["stream_id"])}</text>')
        out.append(f'  <text class="sub" x="{bx + 6}" y="{y + 15}">'
                   f'{_xml_escape(_clip(s["name"], 34))}</text>')

    for i, s in enumerate(wastes):
        wx = BOX_X + BOX_W - 56 - i * 48
        out.append(f'  <path class="wflow" d="M{wx},{BOX_Y + BOX_H} V{WASTE_Y}"/>')
        out.append(f'  <text class="wid" x="{wx + 6}" y="{WASTE_Y - 16}">'
                   f'{_xml_escape(s["stream_id"])}</text>')
        out.append(f'  <text class="sub" x="{wx + 6}" y="{WASTE_Y - 3}">'
                   f'{_xml_escape(_clip(s["name"], 28))}</text>')

    # Instrument bubbles, grouped by attachment point.
    total = len(groups)
    for gi, (label, (ax, ay), rows) in enumerate(groups):
        col = _column_x(gi, total)
        top = BAND_Y - BUBBLE_R - 8
        out.append(f'  <path class="lead" d="M{ax},{ay} L{col},{top}"/>')
        out.append(f'  <text class="sub" x="{col}" y="{top - 4}" text-anchor="middle">'
                   f'at {_xml_escape(label)}</text>')
        for bi, r in enumerate(rows):
            by = BAND_Y + bi * BUBBLE_PITCH
            state = loop_state(r)
            cls = "bubw" if state == "withdrawn" else "bub"
            out.append(f'  <circle class="{cls}" cx="{col}" cy="{by}" r="{BUBBLE_R}"/>')
            letters, _, digits = r["tag"].partition("-")
            out.append(f'  <text class="tag" x="{col}" y="{by - 1}" text-anchor="middle">'
                       f'{_xml_escape(letters)}</text>')
            out.append(f'  <text class="tag" x="{col}" y="{by + 10}" text-anchor="middle">'
                       f'{_xml_escape(digits)}</text>')
            out.append(f'  <text class="sub" x="{col + BUBBLE_R + 5}" y="{by + 4}">'
                       f'{_xml_escape(r["measured_variable"])}, '
                       f'{_xml_escape(r["measurement_mode"])}</text>')
            if state == "closed":
                out.append(f'  <path class="act" d="M{col},{by - BUBBLE_R} '
                           f'L{BOX_X + BOX_W // 2},{BOX_Y + BOX_H}"/>')

    # Legend. Every claim in it is checked against the emitted CSS by a guard.
    ly = BAND_Y + band_h + 14
    out.append(f'  <text class="sub" x="{MARGIN}" y="{ly}">Blue ring = instrument bubble; '
               f'dashed ring = withdrawn sample (at-line or off-line), which no loop can close '
               f'on. Teal arrow to the unit box = the loop acts on this unit.</text>')
    out.append(f'  <text class="sub" x="{MARGIN}" y="{ly + 16}">Grey leader lines point at the '
               f'sensing location and carry no material. Symbols are this project’s own, '
               f'after DEXPI Process 1.0 &#167;6 - not ISA and not ISO 10628-1 '
               f'(Q-053, Q-054).</text>')
    out.append('</svg>')
    return "\n".join(out) + "\n"


def render_page():
    """The host page docs/diagrams/pfd.md, one section per unit operation."""
    equip = {r["equip_id"]: r for r in load_rows("equipment")}
    instruments = load_rows("instruments")

    # Counted, never written out as prose. A hardcoded "nine tags declare control" in the string
    # below would publish to the live site the moment an instrument row changed - a false sentence
    # inside a render() call is still a false sentence on the page.
    n_unit_attached = sum(1 for r in instruments if not (r["stream_ref"] or "").strip())
    declaring = [r for r in instruments if tag_declares_control(r["tag"])]
    n_declare = len(declaring)
    referenced = set()
    for row in load_rows("controls"):
        for token in (row["instrument_ref"] or "").split(";"):
            if token.strip():
                referenced.add(token.strip())
    n_in_register = sum(1 for r in declaring if r["instrument_id"] in referenced)

    out = [BANNER.rstrip("\n"), "", "# Process flow diagrams (PFD)", ""]
    out.append(
        "One diagram per unit operation, generated from the [instrument "
        "register](../registers/instruments.md), the [stream register](../registers/streams.md) "
        "and the [equipment register](../registers/equipment.md). The "
        "[block flow diagram](index.md) is the whole train on one sheet; these are the "
        "instrument-level view of each block in it.")
    out.append("")
    out.append(
        "!!! warning \"The symbol set is this project's own\"\n"
        "    No standard read by this project pins these symbols down. "
        "[DEXPI Process 1.0](../registers/sources.md) supplies the principle — its §6.2.2 says a "
        "PFD symbol represents the *activity* carried out rather than the equipment — but the same "
        "section states that further work is needed to define the presentation layer, so DEXPI "
        "specifies no symbol set. **ISO 10628-1:2014** is the standard that does, and it is "
        "paywalled and **not retrieved**; ANSI/ISA-5.1-2024 governs instrument symbols and is "
        "unread and may not be reproduced. That is **Q-054**, and every drawing says so in its "
        "legend rather than implying conformance.")
    out.append("")
    out.append(
        "!!! note \"What these drawings deliberately do not carry\"\n"
        "    DEXPI §4.3.2 describes a *detailed* PFD as carrying control bubbles, **control "
        "valves** manipulating the flows, and a **stream table**. Neither is drawn here, for "
        "different reasons. No register records which final control element a loop manipulates, so "
        "the actuator arrow stops at the unit box and the gap is **Q-055** — a valve nobody has "
        "specified would be an invention, and would imply equipment that is not in the register. "
        "The stream quantities are not duplicated onto the drawing because they are computed and "
        "already published, scenario by scenario, in the [mass & energy "
        "balance](../balance/results.md). Equipment layout and a plot plan are not here either; "
        "those are a facility exercise tied to Q-002.")
    out.append("")
    out.append("## How to read a bubble")
    out.append("")
    out.append(
        "Each bubble is one instrument, drawn at its sensing point — on a stream, or on the unit "
        "operation itself where the register records no stream. That either/or is DEXPI §2.8.2, "
        f"which is why the {n_unit_attached} instruments with no `stream_ref` attach to the box "
        "instead of being left off. The three states are computed from the register, never "
        "asserted:")
    out.append("")
    out.append(
        "| Bubble | Actuator arrow | Means | Derived from |\n"
        "| --- | --- | --- | --- |\n"
        "| solid ring | yes | a closed loop | the tag declares control **and** the mode is "
        "in-line or on-line |\n"
        "| solid ring | no | indication only | a loop-capable reading whose tag declares no "
        "control |\n"
        "| **dashed ring** | no | a withdrawn sample — no loop can close on it | mode is at-line "
        "or off-line |")
    out.append("")
    out.append(
        "Mode is tested first and wins, so a laboratory result can never acquire an actuator "
        "arrow. That is what keeps **C-013** honest: its instrument `AI-0306` is at-line *and* "
        "carries no control letter, so it renders as a dashed ring with no actuator on two "
        "independent counts. It is a measurement, and the drawing cannot make it look like a "
        "control. See the [control strategy](../process/controls.md) for why.")
    out.append("")
    out.append(
        f"{n_declare} tags declare a control function and all of them render as closed loops, but "
        f"only {n_in_register} appear in the CPP→CQA control register. That is not an error in the "
        "drawing — it is **Q-056**, surfaced by drawing this at all.")
    out.append("")

    for unit in UNITS:
        rows = sorted((r for r in instruments if r["unit_op"] == unit),
                      key=lambda r: r["instrument_id"])
        row = equip.get(unit, {})
        out.append(f"## {unit} — {row.get('name') or unit}")
        out.append("")
        closed = [r for r in rows if loop_state(r) == "closed"]
        withdrawn = [r for r in rows if loop_state(r) == "withdrawn"]
        out.append(
            f"{len(rows)} instrument(s): {len(closed)} closed loop(s), "
            f"{len(withdrawn)} withdrawn-sample measurement(s), "
            f"{len(rows) - len(closed) - len(withdrawn)} indicating only. "
            f"Operation category: {row.get('unit_op') or 'unregistered'}.")
        out.append("")
        out.append('<div markdown="0">')
        out.append(f'--8<-- "diagrams/pfd-{_slug(unit)}.svg"')
        out.append("</div>")
        out.append("")
        out.append(f"[Download the SVG](pfd-{_slug(unit)}.svg)")
        out.append("")

    return "\n".join(out) + "\n"
