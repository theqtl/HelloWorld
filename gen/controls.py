"""CPP -> CQA control matrix, generated from data/controls.csv and data/instruments.csv.

The three "control strategy anchor points" on the tech-transfer page were the whole CPP->CQA
argument and they were PROSE, so nothing in the repo could check them. In particular nothing
could catch a control claimed for a quantity nobody can measure, and the repo contained exactly
that case: Q-042 records that in-line UV saturates on a 21-mer at process concentration, while
the tech-transfer page advertised in-line UV on UF/DF as PAT. Expressing the matrix as data makes
that case representable (control_type `not_measurable`) and makes it fail a test if it is
misrepresented.

Like gen/impurity.py this module is LENIENT on blanks (a blank acceptance basis renders as a
registered gap, never as a control) and STRICT on vocabulary (an unknown control_type raises).
It reads `used_by=docs` parameters only; it computes nothing and it is independent of annual
demand (Q-002), so no number on the generated page is a sizing number.

The instrument vocabularies live here rather than in a module of their own because this is the
only code that reasons about instruments: `controls.instrument_ref` is the single authoritative
link between a control and the thing that enforces it. data/instruments.csv deliberately has no
`control_loop` column - carrying the relation on both sides lets the two disagree with nothing to
detect it, and a monitoring-only instrument is simply one that no control references.
"""
from .dataio import load_rows, load_params

BANNER = ("<!-- GENERATED by gen/controls.py from data/controls.csv and data/instruments.csv - "
          "do not edit by hand. Edit the CSV source instead. -->\n\n")


#: How a control acts. Mirrors CLEARANCE_MODELS in gen/impurity.py: a typo must not fall through
#: to a confident statement about the process.
CONTROL_TYPES = {
    "set_at_supply",       # fixed by the incoming block specification, not adjustable in-facility
    "in_reaction",         # adjusted at the reaction
    "thermal_limit",       # an upper bound on temperature
    "matrix",              # set by the final formulation
    "downstream_removal",  # achieved by a separation step
    "not_measurable",      # NO instrument can measure it at process conditions; renders as a
                           # registered gap. The Q-042 case, and the row type that makes
                           # generating this matrix worth doing at all.
    "gap",                 # no control defined yet
}

#: Control types for which a blank `instrument_ref` is legitimate. A supplier specification has
#: no in-facility instrument; a formulation choice is not an on-line measurement; and a gap or an
#: unmeasurable quantity has, by definition, nothing enforcing it.
INSTRUMENT_OPTIONAL_TYPES = {"set_at_supply", "matrix", "gap", "not_measurable"}

#: Control types that must leave `param_ref` blank. You cannot name the parameter for a quantity
#: nobody can measure, and a `gap` row has no parameter by definition.
PARAM_FORBIDDEN_TYPES = {"not_measurable", "gap"}

#: Where the measurement is taken, per the PAT definitions (ASTM E2363 / ICH Q8): in-line, the
#: sensor sits in the stream and no sample is removed; on-line, a sample is diverted and may be
#: returned; at-line, a sample is removed and measured close by; off-line, a sample goes to a
#: remote laboratory. REQUIRED on every instrument row: without it the Q-042 case cannot be
#: expressed as data, because that case rests entirely on the in-line/at-line distinction.
MEASUREMENT_MODES = {"in_line", "on_line", "at_line", "off_line"}

#: What an instrument measures. Controlled for the same reason as `access` in sources.csv: a
#: misspelling makes the row invisible to anyone filtering the register, and to the guards below.
MEASURED_VARIABLES = {
    "temperature",
    "pressure",
    "differential_pressure",
    "flow",
    "level",
    "conductivity",
    "ph",
    "uv_absorbance",
    "concentration",
    "moisture",
    "gas_humidity",
    "conversion",
    "purity",
    "residual_protein",
    "endotoxin",
    "bioburden",
    "glass_transition",
}

#: Quantities that CANNOT be claimed as an in-line measurement on this stream without a source
#: that establishes it. Q-042 encoded as a rule rather than a note: in-line UV saturates on a
#: 21-mer at process concentration (the required path length is ~10 um), and the answer deployed
#: in the field - variable-pathlength slope spectroscopy - is at-line, not in-line.
NOT_IN_LINE_VARIABLES = {"uv_absorbance", "concentration"}


#: How each control type reads on the page. A control that does not act must not LOOK like one,
#: which is why the last two entries say "registered gap" in the same column the others use to
#: say what they do.
_TYPE_LABEL = {
    "set_at_supply": "set at supply — incoming block specification, not adjustable in-facility",
    "in_reaction": "adjusted at the reaction",
    "thermal_limit": "upper temperature bound",
    "matrix": "set by the final formulation",
    "downstream_removal": "achieved by a separation step",
    "not_measurable": "**not measurable at process conditions** — registered gap",
    "gap": "**no control defined** — registered gap",
}

#: The order quality attributes are presented in: the purity argument first, because it is the
#: one that is decided upstream and cannot be recovered downstream.
_CQA_ORDER = [
    "Full-length purity",
    "Duplex integrity",
    "Residual enzyme protein in the drug substance",
    "Concentration at the UF/DF endpoint",
]


def _esc(text):
    return (text or "").replace("|", "\\|").replace("\n", " ").strip()


def _refs(value):
    return [t.strip() for t in (value or "").split(";") if t.strip()]


def _instrument_cell(row, instruments):
    """Render each instrument as its id, tag and MODE.

    The mode travels with every instrument reference on purpose. The one thing this page has to
    make impossible to miss is that a measurement can exist without being an in-line control, so
    an instrument reference that did not state its mode would give back exactly the ambiguity
    this slice was built to remove.
    """
    out = []
    for iid in _refs(row.get("instrument_ref")):
        inst = instruments.get(iid)
        if inst is None:
            raise ValueError(f"{row['control_id']}: instrument_ref {iid} does not resolve")
        out.append(f"{iid} ({inst['tag']}, {inst['measurement_mode']})")
    return "<br>".join(out) if out else "—"


def _acceptance_cell(row):
    """A blank acceptance basis renders as a REGISTERED gap, never as an empty cell.

    gen/impurity.py established this: a gap the reader cannot follow to a register entry is
    indistinguishable from an oversight.
    """
    basis = (row.get("acceptance_basis") or "").strip()
    if basis:
        return _esc(basis)
    refs = _refs(row.get("gap_ref"))
    assert refs, f"{row['control_id']}: blank acceptance basis with no registered gap"
    return "**gap** (" + ", ".join(refs) + ")"


def render():
    params = load_params()
    rows = load_rows("controls")
    instruments = {r["instrument_id"]: r for r in load_rows("instruments")}

    for r in rows:
        if r["control_type"] not in CONTROL_TYPES:
            raise ValueError(
                f"{r['control_id']}: unknown control_type {r['control_type']!r}; "
                f"expected one of {sorted(CONTROL_TYPES)}"
            )
        for pid in _refs(r.get("param_ref")):
            if pid not in params:
                raise ValueError(f"{r['control_id']}: param_ref {pid} does not resolve")

    body = BANNER + "# Control strategy (CPP → CQA)\n\n"
    body += ("!!! warning \"A structure with flagged placeholders, not an executable control "
             "strategy\"\n"
             "    Almost every acceptance basis below is an **assumption** tied to an open "
             "question, because the data behind Q-010, Q-011, Q-030, Q-039 and Q-050 does not "
             "exist publicly. Rows whose basis is blank render as **registered gaps** with a "
             "live reference, never as a limit. Nothing here is a number a contract manufacturer "
             "could work to; what is checkable is the *structure* — that each control names a "
             "registered parameter, an instrument that could enforce it, and the question that "
             "blocks it.\n\n")

    body += ("This page is generated from `data/controls.csv` and `data/instruments.csv`. It was "
             "prose until Tier 3: three bullets on the "
             "[tech-transfer page](../techtransfer/index.md) carried the whole critical-parameter "
             "argument, and prose cannot be checked. In particular nothing could catch a control "
             "claimed for a quantity nobody can measure — and this repository contained exactly "
             "that case (Q-042). It now has a control type of its own, `not_measurable`, and it "
             "appears below as a gap rather than as a control.\n\n")

    body += ("Every instrument reference carries its **measurement mode**, because the difference "
             "between an in-line reading and an at-line one is the difference between a control "
             "loop and a laboratory result. The full instrument list, control-enforcing and "
             "monitoring-only alike, is the "
             "[instrument register](../registers/instruments.md); the raw rows behind this page "
             "are the [control register](../registers/controls.md).\n\n")

    cols = ["Critical process parameter", "Acts", "Acceptance basis", "Unit op",
            "Parameter", "Equation", "Instrument (tag, mode)", "Risk", "Gap", "Provenance"]

    seen = set()
    order = _CQA_ORDER + [c for c in (r["cqa"] for r in rows) if c not in _CQA_ORDER]
    for cqa in order:
        if cqa in seen:
            continue
        seen.add(cqa)
        group = [r for r in rows if r["cqa"] == cqa]
        if not group:
            continue
        body += f"## {cqa}\n\n"
        lines = ["| " + " | ".join(cols) + " |",
                 "| " + " | ".join("---" for _ in cols) + " |"]
        for r in group:
            prov = r["provenance"]
            src = (r.get("source_key") or "").strip()
            cells = [
                f"**{r['control_id']}** — {_esc(r['cpp'])}",
                _TYPE_LABEL[r["control_type"]],
                _acceptance_cell(r),
                _esc(r["unit_op"]),
                ", ".join(_refs(r.get("param_ref"))) or "—",
                ", ".join(_refs(r.get("equation_ref"))) or "—",
                _instrument_cell(r, instruments),
                ", ".join(_refs(r.get("risk_ref"))) or "—",
                ", ".join(_refs(r.get("gap_ref"))) or "—",
                f"{prov} ({src})" if src else prov,
            ]
            lines.append("| " + " | ".join(cells) + " |")
        body += "\n".join(lines) + "\n\n"
        for r in group:
            body += f"- **{r['control_id']}** — {_esc(r['notes'])}\n"
        body += "\n"

    body += ("## What this page does not do\n\n"
             "It does not choose the ligase, and it must not read as though it had: enzyme form "
             "is open (Q-050), so enzyme clearance is carried as **two branches with blank "
             "acceptance**, and neither is the selected route. It does not size anything — "
             "control strategy is a set of limits and is independent of annual demand (Q-002). "
             "And it does not close a single one of the questions its rows point at; it makes "
             "them countable.\n")
    return body
