"""CPP -> CQA control matrix, generated from data/controls.csv and data/instruments.csv.

The three "control strategy anchor points" on the tech-transfer page were the whole CPP->CQA
argument and they were PROSE, so nothing in the repo could check them. In particular nothing
could catch a control whose measurement does not exist on this stream, and the repo contained
exactly that case: Q-042 records that in-line UV saturates on a 21-mer at process concentration,
while the tech-transfer page advertised in-line UV on UF/DF as PAT. Expressing the matrix as data
makes that case representable (control_type `at_line_only`) and makes it fail a test if it is
misrepresented.

The reason it is `at_line_only` rather than `not_measurable` is a correction: variable-pathlength
slope spectroscopy is NOT inherently at-line. FlowVPE publishes 5 um - 8 mm and is used in-line on
UF/DF in the peer-reviewed literature (SRC-ROLINGER-2023, open access). What is true is narrower
and quantitative - at OUR registered retentate concentration the pathlength an A260 = 1 reading
needs falls BELOW that published floor - so the at-line choice rests on arithmetic against a
parameter, not on a categorical claim about the technique. `required_pathlength_um` computes it.

Like gen/impurity.py this module is LENIENT on blanks (a blank acceptance basis renders as a
registered gap, never as a control) and STRICT on vocabulary (an unknown control_type raises).
It reads `used_by=docs` parameters only; it computes nothing and it is independent of annual
demand (Q-002), so no number on the generated page is a sizing number.

The instrument vocabularies live here rather than in a module of their own because this is the
only code that reasons about instruments: `controls.instrument_ref` is the single authoritative
link between a control and the thing that enforces it. data/instruments.csv deliberately has no
`control_loop` column - carrying the relation on both sides lets the two disagree with nothing to
detect it, and a monitoring-only instrument is simply one that no control references.
"""
