#: Quantities whose in-line feasibility is a matter of OPTICAL GEOMETRY rather than of instrument
#: availability, so an in-line claim for one of them has to be justified rather than asserted. The
#: earlier name for this set said such a reading was impossible; that was wrong - variable-pathlength
#: cells ARE used in-line (SRC-ROLINGER-2023) - and the rule is now the arithmetic below: a reading
#: is geometrically possible only where the pathlength it needs is at or above the published floor
#: for an in-line cell (P-VPE-PATHLENGTH-MIN).
OPTICAL_CONCENTRATION_VARIABLES = {"uv_absorbance", "concentration"}


def required_pathlength_um(params, conc_g_per_L):
    """Pathlength band, in microns, that an A260 = 1 reading needs at `conc_g_per_L`.

    L = 1 / (eps * C) from Beer-Lambert, with eps as a BAND (P-EPS-260) because the coefficient is
    sequence-specific, so the answer is a band too. Returns (lo, hi) or None if either input is a
    registered blank - lenient, like the rest of this module: a missing number renders as a gap, it
    never becomes a fabricated one.
    """
    lo_eps = _param_float(params, "P-EPS-260", "range_low")
    hi_eps = _param_float(params, "P-EPS-260", "range_high")
    if lo_eps is None or hi_eps is None or not conc_g_per_L:
        return None
    # g/L is numerically mg/mL, which is what eps is per. 1 cm = 10_000 um.
    return (1.0 / (hi_eps * conc_g_per_L) * 1e4, 1.0 / (lo_eps * conc_g_per_L) * 1e4)


def in_line_optical_possible(params, conc_g_per_L):
    """True if an in-line optical reading is geometrically possible at this concentration.

    False only when the WHOLE required band sits below the published in-line floor, so an ambiguous
    band never decides the question. None if anything needed is blank.
    """
    band = required_pathlength_um(params, conc_g_per_L)
    floor = _param_float(params, "P-VPE-PATHLENGTH-MIN", "value")
    if band is None or floor is None:
        return None
    return band[1] >= floor


def tag_letter_error(tag):
    """Why `tag` is not a legal tag under TAG_FIRST_LETTERS, or None if it is legal.

    Checks the letters BY POSITION, which is the whole point: the guard this replaced held an
    allow-list of the prefixes that already existed, so it could only ever bless them. `DPI` passed
    that allow-list and is wrong; `PDI` is right, and a position check reaches that conclusion from
    the scheme instead of from the data.
    """
    if not re.fullmatch(TAG_PATTERN, tag):
        return f"not of the form <letters>-<unit><loop>: {tag!r}"
    letters = tag.split("-")[0]
    first, rest = letters[0], letters[1:]
    if first not in TAG_FIRST_LETTERS:
        legal = "/".join(sorted(TAG_FIRST_LETTERS))
        modifier = " (a variable modifier, so it cannot lead - did you mean P+D, i.e. PDI?)" \
            if first in TAG_VARIABLE_MODIFIERS else ""
        return f"first letter {first!r} is not a declared variable{modifier}; declared: {legal}"
    for i, ch in enumerate(rest):
        if ch in TAG_VARIABLE_MODIFIERS:
            if i != 0:
                return (f"variable modifier {ch!r} must sit immediately after the first letter, "
                        f"not at position {i + 2} of {letters!r}")
            continue
        if ch in TAG_READOUT_LETTERS or ch in TAG_OUTPUT_LETTERS:
            continue
        return f"letter {ch!r} in {letters!r} is not declared in any succeeding position"
    return None


def tag_scheme_markdown():
    """The declared tag scheme, rendered for the instrument register.

    Published because an undeclared user's-choice letter is indistinguishable from a mistake, and
    because a reader has to be able to see that this is OUR scheme rather than a standard one.
    """
    out = ("## Tag letters — this project's declared scheme\n\n"
           "These letters are **this repository's**, not a reproduction of any standard's table. "
           "ANSI/ISA-5.1-2024 is paywalled and was not retrieved, its identification guidance moved "
           "into ISA-TR5.1.02-2024 which was also not retrieved, and ISA prohibits entering its "
           "material into AI tools — so conformance to the current edition is **unverified** and is "
           "registered as Q-053 ([SRC-ISA-5-1-2024](sources.md)). Buy both documents into document "
           "control and check this table against them before any P&ID is issued.\n\n")
    out += md_table(
        [{"Position": "first letter (the measured variable)", "Letter": f"`{k}`", "Means": v}
         for k, v in sorted(TAG_FIRST_LETTERS.items())]
        + [{"Position": "variable modifier (immediately after the first letter)",
            "Letter": f"`{k}`", "Means": v} for k, v in sorted(TAG_VARIABLE_MODIFIERS.items())]
        + [{"Position": "readout / passive function", "Letter": f"`{k}`", "Means": v}
           for k, v in sorted(TAG_READOUT_LETTERS.items())]
        + [{"Position": "output / active function", "Letter": f"`{k}`", "Means": v}
           for k, v in sorted(TAG_OUTPUT_LETTERS.items())])
    out += ("\nTwo of the first letters are assignments this project makes for itself, because the "
            "convention leaves them to the user: **M** for moisture or humidity, and **Q** for a "
            "discrete sampled quantity. They are declared here precisely so they cannot be mistaken "
            "for standard meanings — and so that a genuine error is visible. `DPI` for differential "
            "pressure was exactly that error: `D` modifies a variable and cannot lead, so the tag is "
            "`PDI`.\n\n"
            "The four-digit block after the letters is `<unit><loop>` and is also ours: area and "
            "unit prefixes are not specified by the convention at all.\n\n")
    return out


def _param_float(params, pid, field):
    row = params.get(pid)
    if not row:
        return None
    raw = (row.get(field) or "").strip()
    try:
        return float(raw)
    except ValueError:
        return None


#: The streams an in-line optical concentration reading might be wanted on, in train order, each
#: with the registered concentration that decides whether it is geometrically possible.
_OPTICAL_STREAMS = [
    ("Ligation reactor", "P-CONC-LIG"),
    ("UF/DF retentate", "P-CONC-UF"),
    ("Evaporator outlet", "P-CONC-EVAP"),
]


def _pathlength_table(params):
    """Render the pathlength arithmetic, so the at-line decision is shown rather than asserted.

    This is the whole justification for C-013 being `at_line_only`, and putting it on the page as a
    computed table means it cannot quietly go stale: change P-CONC-UF or P-VPE-PATHLENGTH-MIN and
    both the table and the guard that checks it move together.
    """
    floor = _param_float(params, "P-VPE-PATHLENGTH-MIN", "value")
    rows = []
    for label, pid in _OPTICAL_STREAMS:
        conc = _param_float(params, pid, "value")
        band = required_pathlength_um(params, conc) if conc else None
        if band is None or floor is None:
            verdict = "gap — a required input is blank (Q-052)"
            band_text = "—"
        else:
            band_text = f"{band[0]:.1f} – {band[1]:.1f}"
            verdict = ("possible in-line" if band[1] >= floor
                       else "**below the published floor — at-line only**")
        rows.append({
            "Stream": label,
            "Concentration": f"`{pid}`" + (f" = {conc:g} g/L" if conc else " (blank)"),
            "Pathlength needed for A260 = 1 (µm)": band_text,
            "Against the in-line floor": verdict,
        })
    out = ("Where an in-line optical concentration reading is geometrically possible, computed from "
           "`P-EPS-260` (a band, because the coefficient is sequence-specific — Q-052) against "
           "`P-VPE-PATHLENGTH-MIN`:\n\n")
    out += md_table(rows)
    return out + "\n"


#: THIS REPOSITORY'S instrument-tag letter scheme. It is NOT a reproduction of any ISA table.
#:
#: ANSI/ISA-5.1-2024 is paywalled and was not retrieved (SRC-ISA-5-1-2024), its identification
#: guidance was split out into ISA-TR5.1.02-2024 which was also not retrieved, and ISA prohibits
#: entering its intellectual property into AI tools - so no letter table from it may be reproduced
#: here and conformance to it is UNVERIFIED (Q-053). What follows is the scheme this project
#: declares for the letters it actually uses, written so a wrong letter can be caught by position
#: rather than by an allow-list of whatever tags happen to exist.
#:
#: Two entries are this project's own assignments of letters that the widely-followed convention
#: leaves to the user, and they are called out as such rather than presented as standard:
#:   M = moisture / humidity          (2 rows: I-039, I-040)
#:   Q = discrete sampled quantity    (8 rows: bioburden, endotoxin, glass transition)
#: Declaring them is the point. An undeclared user's-choice letter is indistinguishable from a
#: mistake, which is exactly how `DPI-` (D is a MODIFIER, not a variable) survived review.
TAG_FIRST_LETTERS = {
    "T": "temperature",
    "P": "pressure",
    "F": "flow",
    "L": "level",
    "A": "analysis (composition, conductivity, absorbance)",
    "M": "moisture / humidity — THIS PROJECT'S user's-choice assignment",
    "Q": "discrete sampled quantity — THIS PROJECT'S user's-choice assignment",
}

#: Letters that may modify the variable, and must sit immediately after the first letter.
TAG_VARIABLE_MODIFIERS = {"D": "difference / differential"}

#: Readout or passive functions, after the variable and its modifier.
TAG_READOUT_LETTERS = {"I": "indicate", "R": "record"}

#: Output or active functions, last. This is why differential pressure is PDI and never DPI: the
#: differential letter modifies P, so it cannot lead.
TAG_OUTPUT_LETTERS = {"C": "control", "T": "transmit"}

#: Area and unit prefixes are NOT specified by the convention at all - the user is free to add
#: them - so the four-digit <unit><loop> block below is this project's own and must not be
#: attributed to ISA (Q-053).
TAG_PATTERN = r"[A-Z]{2,4}-\d{4}"


#: How each control type reads on the page. A control that does not act must not LOOK like one,
#: which is why the last two entries say "registered gap" in the same column the others use to
#: say what they do.
_TYPE_LABEL = {
    "set_at_supply": "set at supply — incoming block specification, not adjustable in-facility",
    "in_reaction": "adjusted at the reaction",
    "thermal_limit": "upper temperature bound",
    "matrix": "set by the final formulation",
    "downstream_removal": "achieved by a separation step",
    "at_line_only": "at-line only — judged on a withdrawn sample; **the loop is open**",
    "not_measurable": "**not measurable at process conditions** — registered gap",
    "gap": "**no control defined** — registered gap",
}

#: The order quality attributes are presented in: the purity argument first, because it is the
#: one that is decided upstream and cannot be recovered downstream.
_CQA_ORDER = [
    "Full-length purity",
    "Duplex integrity",
    "Residual enzyme protein in the drug substance",
    "Concentration at the UF/DF endpoint",
]


def _esc(text):
    return (text or "").replace("|", "\\|").replace("\n", " ").strip()


def _refs(value):
    return [t.strip() for t in (value or "").split(";") if t.strip()]


def _instrument_cell(row, instruments):
    """Render each instrument as its id, tag and MODE.

    The mode travels with every instrument reference on purpose. The one thing this page has to
    make impossible to miss is that a measurement can exist without being an in-line control, so
    an instrument reference that did not state its mode would give back exactly the ambiguity
    this slice was built to remove.
    """
    out = []
    for iid in _refs(row.get("instrument_ref")):
        inst = instruments.get(iid)
        if inst is None:
            raise ValueError(f"{row['control_id']}: instrument_ref {iid} does not resolve")
        out.append(f"{iid} ({inst['tag']}, {inst['measurement_mode']})")
    return "<br>".join(out) if out else "—"


def _acceptance_cell(row):
    """A blank acceptance basis renders as a REGISTERED gap, never as an empty cell.

    gen/impurity.py established this: a gap the reader cannot follow to a register entry is
    indistinguishable from an oversight.
    """
    basis = (row.get("acceptance_basis") or "").strip()
    if basis:
        return _esc(basis)
    refs = _refs(row.get("gap_ref"))
    assert refs, f"{row['control_id']}: blank acceptance basis with no registered gap"
    return "**gap** (" + ", ".join(refs) + ")"


def render():
    params = load_params()
    rows = load_rows("controls")
    instruments = {r["instrument_id"]: r for r in load_rows("instruments")}

    for r in rows:
        if r["control_type"] not in CONTROL_TYPES:
            raise ValueError(
                f"{r['control_id']}: unknown control_type {r['control_type']!r}; "
                f"expected one of {sorted(CONTROL_TYPES)}"
            )
        for pid in _refs(r.get("param_ref")):
            if pid not in params:
                raise ValueError(f"{r['control_id']}: param_ref {pid} does not resolve")

    body = BANNER + "# Control strategy (CPP → CQA)\n\n"
    body += ("!!! warning \"A structure with flagged placeholders, not an executable control "
             "strategy\"\n"
             "    Almost every acceptance basis below is an **assumption** tied to an open "
             "question, because the data behind Q-010, Q-011, Q-030, Q-039 and Q-050 does not "
             "exist publicly. Rows whose basis is blank render as **registered gaps** with a "
             "live reference, never as a limit. Nothing here is a number a contract manufacturer "
             "could work to; what is checkable is the *structure* — that each control names a "
             "registered parameter, an instrument that could enforce it, and the question that "
             "blocks it.\n\n")

    body += ("This page is generated from `data/controls.csv` and `data/instruments.csv`. It was "
             "prose until Tier 3: three bullets on the "
             "[tech-transfer page](../techtransfer/index.md) carried the whole critical-parameter "
             "argument, and prose cannot be checked. In particular nothing could catch a control "
             "whose measurement does not exist on this stream — and this repository contained "
             "exactly that case (Q-042). It now has a control type of its own, `at_line_only`, "
             "and it appears below as an **open loop** rather than as a control.\n\n")

    body += ("!!! note \"Why `at_line_only` and not `not measurable`\"\n"
             "    An earlier reading of Q-042 held that variable-pathlength slope spectroscopy is "
             "inherently at-line. That was wrong: FlowVPE publishes a 5 µm–8 mm pathlength range "
             "and is used **in-line** on UF/DF in the peer-reviewed literature "
             "([SRC-ROLINGER-2023](../registers/sources.md), open access). The true constraint is "
             "narrower and it is arithmetic — at the registered retentate concentration "
             "(`P-CONC-UF`) an A260 = 1 reading needs a pathlength below that published floor "
             "(`P-VPE-PATHLENGTH-MIN`), so the reading has to come off a withdrawn sample **here**, "
             "on **this** stream. It is a project constraint against a vendor specification, not a "
             "property of the technique. Note also that variable-pathlength instruments saturate "
             "near their own floor, and the documented failure mode is *underestimation* of "
             "concentration — a silent, non-conservative bias (Q-051).\n\n")

    body += _pathlength_table(params)

    body += ("Every instrument reference carries its **measurement mode**, because the difference "
             "between an in-line reading and an at-line one is the difference between a control "
             "loop and a laboratory result. The full instrument list, control-enforcing and "
             "monitoring-only alike, is the "
             "[instrument register](../registers/instruments.md); the raw rows behind this page "
             "are the [control register](../registers/controls.md).\n\n")

    cols = ["Critical process parameter", "Acts", "Acceptance basis", "Unit op",
            "Parameter", "Equation", "Instrument (tag, mode)", "Risk", "Gap", "Provenance"]

    seen = set()
    order = _CQA_ORDER + [c for c in (r["cqa"] for r in rows) if c not in _CQA_ORDER]
    for cqa in order:
        if cqa in seen:
            continue
        seen.add(cqa)
        group = [r for r in rows if r["cqa"] == cqa]
        if not group:
            continue
        body += f"## {cqa}\n\n"
        lines = ["| " + " | ".join(cols) + " |",
                 "| " + " | ".join("---" for _ in cols) + " |"]
        for r in group:
            prov = r["provenance"]
            src = (r.get("source_key") or "").strip()
            cells = [
                f"**{r['control_id']}** — {_esc(r['cpp'])}",
                _TYPE_LABEL[r["control_type"]],
                _acceptance_cell(r),
                _esc(r["unit_op"]),
                ", ".join(_refs(r.get("param_ref"))) or "—",
                ", ".join(_refs(r.get("equation_ref"))) or "—",
                _instrument_cell(r, instruments),
                ", ".join(_refs(r.get("risk_ref"))) or "—",
                ", ".join(_refs(r.get("gap_ref"))) or "—",
                f"{prov} ({src})" if src else prov,
            ]
            lines.append("| " + " | ".join(cells) + " |")
        body += "\n".join(lines) + "\n\n"
        for r in group:
            body += f"- **{r['control_id']}** — {_esc(r['notes'])}\n"
        body += "\n"

    body += ("## What this page does not do\n\n"
             "It does not choose the ligase, and it must not read as though it had: enzyme form "
             "is open (Q-050), so enzyme clearance is carried as **two branches with blank "
             "acceptance**, and neither is the selected route. It does not size anything — "
             "control strategy is a set of limits and is independent of annual demand (Q-002). "
             "And it does not close a single one of the questions its rows point at; it makes "
             "them countable.\n")
    return body
